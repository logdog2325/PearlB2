@functools.lru_cache(maxsize=None)
def entrances(ver=None):
    """[(room, door tile (x, z), model, origin (x, z) in matrix units, solid tiles)] of the version's rooms."""
    d = load()
    out = []
    for r in rooms(ver):
        mid = entrance_model(d, next(x for x in d['rooms'] if x['id'] == r['id']))
        x0, x1, z0, z1 = model_box(mid)
        dx, dz = r['entrance']['x'], r['entrance']['z']
        ox, oz = dx * 16 + 8, (dz + 1) * 16 - z1                 # the front face on the door tile's south edge
