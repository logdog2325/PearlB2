# Called by b2tools/pearl_story.py (gate and park script files) and b2tools/pearl_events.py (their people and
# frame tables). Pearl's own scripts stay as Pearl's; these come after them.

def zone_extras(zone_name):
    """The extra script entries of a Pearl zone, in order: ['clerk', 'return'] for the gate, ['attendant'] for the
    park, [] elsewhere."""
    d = load()
    if zone_name == d['gate']:
        return ['clerk', 'return']
    if zone_name == d['pal_park']:
        return ['attendant']
    return []


def extra_people(zone_name, ids):
    """New people of a Pearl zone: [{pearl-like object}] with 'script' = the extra entry's id (ids: {extra: id})."""
    d = load()
    if zone_name != d['gate']:
        return []
    cl = d['clerk']
    return [dict(id=100, graphics_id=cl['pearl_gfx'], movement_type=0, trainer_type=0, hidden_flag=0,
                 script=ids['clerk'], initial_dir=cl['dir'], data=[0, 0, 0], movement_range_x=0, movement_range_z=0,
                 x=cl['x'], z=cl['z'], y=0)]


def talk_override(zone_name, ids):
    """{Pearl object id: extra entry id} of people whose talk script an extra entry runs first."""
    d = load()
    if zone_name == d['pal_park']:
        return {0: ids['attendant']}           # the park's attendant (Pearl's "retire from the Catching Show?")
    return {}


def frame_rows(zone_name, ids):
    """[(Black 2 work, value, entry id)] added to a Pearl zone's frame table (after Pearl's rows)."""
    d = load()
    if zone_name == d['gate']:
        return [(pearl_var(d['show_var']), d['show_values']['ramanas'], ids['return'])]
    return []


def gate_movements(pd):
    """Pearl's own movement lists of the Catching Show's entry and return (Pearl script file 444): the receptionist
    steps aside (0x02B8) and back (0x03D8), the player walks in (0x02CC) and out (0x03E4)."""
    import pearl_story
    f = pd.by_name[load()['gate']]['scripts']
    return {k: pearl_story.movement_steps(pd, f, a) for k, a in
            (('aside', 0x02B8), ('in', 0x02CC), ('back', 0x03D8), ('out', 0x03E4))}


