# ------------------------------------------------------------------------------------------------------- data

def load():
    return json.load(open(DATA, encoding='utf-8'))


def version(d=None):
    return os.environ.get('PEARL_VERSION') or (d or load())['version']


_CONSTS = {}


def consts(kind):
    """{NAME: number} of a decomp constants file (generated/<kind>.txt: 'NAME = n' starts, the next lines count up)."""
    if kind not in _CONSTS:
        out, cur = {}, -1
        for line in open(os.path.join(DECOMP, 'generated', f'{kind}.txt'), encoding='utf-8'):
            line = line.split('#')[0].strip()
            if not line:
                continue
            if '=' in line:
                name, v = (s.strip() for s in line.split('=', 1))
                cur = int(v, 0)
            else:
                name, cur = line, cur + 1
            out[name] = cur
        _CONSTS[kind] = out
    return _CONSTS[kind]


def const(kind, name):
    c = consts(kind)
    assert name in c, f'{name}: not in the decomp\'s generated/{kind}.txt'
    return c[name]


def new_flags():
    """{PFLAG name: Black 2 flag} of the registry's new flags (b2tools/pearl_ids.py NEW_FLAGS)."""
    reg = json.load(open(REGISTRY))
    return {k: v['b2'] for k, v in reg.get('new_flags', {}).items()}


def pearl_flag(name):
    """A Black 2 flag by its pearl.h name: PFLAG_xxxx (Pearl's, through the registry) or a new one."""
    nf = new_flags()
    if name in nf:
        return nf[name]
    reg = json.load(open(REGISTRY))
    m = re.match(r'PFLAG_([0-9A-F]{4})$', name)
    assert m and f'0x{m.group(1)}' in reg['flags'], f'{name}: no such flag in the registry'
    return reg['flags'][f'0x{m.group(1)}']['b2']


def pearl_var(name):
    reg = json.load(open(REGISTRY))
    m = re.match(r'PVAR_([0-9A-F]{4})$', name)
    assert m and f'0x{m.group(1)}' in reg['vars'], f'{name}: no such var in the registry'
    return int(reg['vars'][f'0x{m.group(1)}']['b2'], 16)


def in_version(room, ver):
    return room['version'] in ('both', ver)


def requires(room, ver):
    r = room['requires']
    return r.get(ver, []) if isinstance(r, dict) else r


def rooms(ver=None):
    """The version's rooms, resolved: numbers for species, moves, items, sprites, flags (in data order)."""
    d = load()
    ver = ver or version(d)
    out = []
    for room in d['rooms']:
        if not in_version(room, ver):
            continue
        mons = []
        for p in room['pokemon']:
            mons.append(dict(
                species=const('species', p['species']), name=p['species'][8:].replace('_', '-').title(),
                level=p.get('level', d['level']), form=p.get('form', 0), hidden=p['hidden_ability'],
                no_capture=p.get('no_capture', False), flag_name=p['flag'], sprite=const('obj_codes', p['sprite']),
                moves=[const('moves', m) for m in p['moves']],
                items=[const('items', i) for i in p.get('items', [])],
                win_items=[const('items', i) for i in p.get('win_items', [])]))
        out.append(dict(id=room['id'], name=room['name'], zone=room['zone'], look=room['look'], pick=room['pick'],
                        slate=room['slate']['item'], slate_name=room['slate']['name'],
                        requires=requires(room, ver), requires_flags=room['requires_flags'],
                        entrance=room['entrance'], complete_items=[const('items', i) for i in
                                                                    room.get('complete_items', [])],
                        mons=mons))
    ids = {r['id'] for r in out}
    for r in out:
        assert all(q in ids for q in r['requires']), f'{r["id"]}: requires a room not in version {ver}'
    return out


def flag_of(m):
    return pearl_flag(m['flag_name'])


# ------------------------------------------------------------------------------------------------------- text

def fill(text, **kw):
    for k, v in kw.items():
        text = text.replace('{' + k + '}', v)
    return text


def b2(text):
    """A line in Pearl markup (\\n, \\r a new page, {STRVAR_1 k, i} buffers) as a Black 2 text line."""
    import gen4_text
    return gen4_text.b2_line(text)


def check_width(text, where):
    """Every line of a message fits the plain window (WINDOW_PX); buffers counted as 12 characters."""
    import b2font
    font = b2font.load(0)
    bad = []
    for seg in re.split(r'\\[nrf]', text):
        seg = re.sub(r'\{STRVAR_1 [^}]*\}', 'MMMMMMMMMMMM', seg)
        if font.width(seg) > WINDOW_PX:
            bad.append(f'{where}: "{seg}" is {font.width(seg)} px (the window shows {WINDOW_PX})')
    return bad


class Text:
    """The rooms' text file: lines by key, kept once."""

    def __init__(self):
        self.lines, self.index = [], {}

    def line(self, key, text):
        if key not in self.index:
            self.index[key] = len(self.lines)
            self.lines.append(text)
        return self.index[key]


# ------------------------------------------------------------------------------------------------------- code

class Code:
    def __init__(self, prefix):
        self.out, self.prefix, self.n = [], prefix, 0

    def label(self, what=''):
        self.n += 1
        return f'.L{self.prefix}_{self.n}{what}'

    def __call__(self, *lines):
        self.out += list(lines)

    def at(self, label):
        self.out.append(f'{label}:')

    def jump_if_flag(self, flag, value, label):
        """Go to label when the flag is (value 1) set / (0) clear."""
        self(f'    FlagGet {flag}, 0x{T[7]:04X}', f'    WorkCmpConst 0x{T[7]:04X}, {value}',
             f'    VMJumpIf CMP_EQ, {label}')

    def msg_end(self, line, talk=False):
        """A message, then the end of the script."""
        self(f'    {"pl_msg_talk" if talk else "pl_msg_sys"} {line}', '    pl_WaitButton', '    pl_CloseMessage',
             '    pl_ReleaseAll', '    VMHalt')

    def give(self, item, count=1):
        """Black 2's item-get (global ITEM_GET, as its own scripts call it)."""
        self('    VMStackPush 0x8000', '    VMStackPush 0x8001', f'    WorkSetConst 0x8000, {item}',
             f'    WorkSetConst 0x8001, {count}', f'    RTCallGlobal {ITEM_GET}', '    VMStackPop 0x8001',
             '    VMStackPop 0x8000')


def room_complete_code(c, room, label_not_done):
    """Jump to label_not_done unless every Pokémon of the room is caught (Distortion: won once)."""
    for m in room['mons']:
        c.jump_if_flag(flag_of(m), 0, label_not_done)


def room_open_code(c, room, by_id, open_flag, label_closed):
    """Jump to label_closed unless the room is open: the park open (open_flag), each required room complete, each
    required flag set."""
    c.jump_if_flag(open_flag, 0, label_closed)
    for q in room['requires']:
        for m in by_id[q]['mons']:
            c.jump_if_flag(flag_of(m), 0, label_closed)
    for f in room['requires_flags']:
        c.jump_if_flag(pearl_flag(f), 0, label_closed)


def wild_flags(m):
    return WILD_LEGEND | (WILD_HIDDEN_ABILITY if m['hidden'] else 0)


def pedestal_code(c, room, i, tx, d, park_state):
    """Room i's pedestal script (entry 1 + 4i)."""
    t0, t1, t2, t3 = (f'0x{w:04X}' for w in T[:4])
    slate = room['slate_name']
    L = lambda k, **kw: tx.line((room['id'], k), fill(d['text'][k], slate=f'{slate}', room=room['name'], **kw))
    not_done, have, end = c.label('notdone'), c.label('have'), c.label('end')
    c.at(f'RP_Pedestal_{i}')
    c('    pl_LockAll')
    room_complete_code(c, room, not_done)
    c.msg_end(L('pedestal_done'))
    c.at(not_done)
    c(f'    ItemCheckAmount {room["slate"]}, 1, {t0}', f'    WorkCmpConst {t0}, 1', f'    VMJumpIf CMP_EQ, {have}')
    c.msg_end(L('pedestal_empty'))
    c.at(have)
    c(f'    pl_msg_sys {L("pedestal_ask")}', f'    YesNoWin {t0}', f'    WorkCmpConst {t0}, 0',
      f'    VMJumpIf CMP_NE, {end}')
    mons = room['mons']
    # which Pokémon -> t1 = its index
    chosen = c.label('chosen')
    if room['pick'] == 'one' or len(mons) == 1:
        c(f'    WorkSetConst {t1}, 0')
    elif room['pick'] == 'random':
        c(f'    WorkSetConst {t2}, 0')                                    # t2 = how many are left
        for m in mons:
            skip = c.label()
            c.jump_if_flag(flag_of(m), 1, skip)
            c(f'    WorkAdd {t2}, 1')
            c.at(skip)
        c(f'    Random {t3}, {t2}')                                         # the t3-th of the uncaught
        for k, m in enumerate(mons):
            skip = c.label()
            c.jump_if_flag(flag_of(m), 1, skip)
            c(f'    WorkSetConst {t1}, {k}', f'    WorkCmpConst {t3}, 0', f'    VMJumpIf CMP_EQ, {chosen}',
              f'    WorkSub {t3}, 1')
            c.at(skip)
    elif room['pick'] == 'choose':
        c('    pl_CloseMessage', f'    pl_msg_sys {L("pedestal_choose")}',
          f'    ListMenu_AnchorTopRight {LIST_X}, {LIST_Y}, 0, 1, {t1}')
        name_line = tx.line(('species_buffer',), '{STRVAR_1 0, 0}')
        for k, m in enumerate(mons):
            skip = c.label()
            c.jump_if_flag(flag_of(m), 1, skip)
            c(f'    WordSetPokeSpecies 0, {m["species"]}', f'    ListMenuAdd {name_line}, 65535, {k}')
            c.at(skip)
        c('    ListMenuShow', f'    WorkCmpConst {t1}, {len(mons)}', f'    VMJumpIf CMP_GE, {end}')
    else:
        raise ValueError(room['pick'])
    c.at(chosen)
    c('    pl_CloseMessage', f'    ItemSub {room["slate"]}, 1, {t0}', f'    pl_msg_sys {L("pedestal_glow")}',
      '    pl_WaitButton', '    pl_CloseMessage')
    if d['looks'][room['look']].get('step_back'):     # the Pokémon appears where the player stood: one step back first
        c('    ActorCmdExec PL_PLAYER, RP_MovStepBack', '    ActorCmdWait')
    c('    FadeOutWhite', '    FadeWait')
    for k, m in enumerate(mons):
        nxt = c.label()
        c(f'    WorkCmpConst {t1}, {k}', f'    VMJumpIf CMP_NE, {nxt}')
        uid = k + 1
        c(f'    FlagReset {SPRITE_FLAG + k}', f'    ActorAdd {uid}', '    FadeInWhite', '    FadeWait',
          f'    PVPlay {m["species"]}, 0', '    PVWait',
          f'    CallWildBattleEx {m["species"]}, {m["level"]}, {m["form"]}, {wild_flags(m)}',
          f'    WildBattleIsVictory {t0}', f'    WorkCmpConst {t0}, 1', f'    VMJumpIf CMP_NE, .LRP_lost_{i}',
          f'    ActorDelete {uid}', f'    FlagSet {SPRITE_FLAG + k}', '    CallWildBattleEnd',
          f'    WildBattleGetResult {t0}')
        done = c.label()
        if m['no_capture']:
            c(f'    WorkCmpConst {t0}, 2', f'    VMJumpIf CMP_NE, {done}', f'    FlagSet {flag_of(m)}',
              f'    pl_msg_sys {L("after_win")}', '    pl_WaitButton', '    pl_CloseMessage')
            for it in m['win_items']:
                c.give(it)
        else:
            c(f'    WorkCmpConst {t0}, 0', f'    VMJumpIf CMP_NE, {done}', f'    FlagSet {flag_of(m)}')
            if m['items']:
                c(f'    pl_msg_sys {L("berries_left")}', '    pl_WaitButton', '    pl_CloseMessage')
                for it in m['items']:
                    c.give(it)
            if room['complete_items']:
                not_all = c.label()
                room_complete_code(c, room, not_all)
                for it in room['complete_items']:
                    c.give(it)
                c.at(not_all)
        c.at(done)
        c('    pl_ReleaseAll', '    VMHalt')
        c.at(nxt)
    c.at(end)
    c('    pl_CloseMessage', '    pl_ReleaseAll', '    VMHalt')
    c.at(f'.LRP_lost_{i}')
    c(f'    WorkSetConst 0x{park_state:04X}, 0', '    CallWildLose', '    VMHalt')


def write_rooms(ver=None):
    """The rooms' script and text (one file each for every room of the version)."""
    d = load()
    ver = ver or version(d)
    rs = rooms(ver)
    by_id = {r['id']: r for r in rs}
    park_state = pearl_var(d['show_var'])
    tx = Text()
    c = Code('RP')
    entries = []
    for i, room in enumerate(rs):
        entries += [f'RP_Pedestal_{i}', f'RP_Init_{i}', f'RP_Name_{i}', f'RP_Closed_{i}']
    head = ['// The slate rooms of Ramanas Park in Pal Park (notes/RAMANAS_PARK.md). Written by b2tools/ramanas.py from',
            '// data/ramanas_park.json: do not edit; rerun `python3 b2tools/ramanas.py`.',
            f'// Version {ver}. Room i: entries {", ".join(f"{1 + 4 * i}-{4 + 4 * i} {r["name"]} (zone {r["zone"]})" for i, r in enumerate(rs))}',
            '// (pedestal, zone init, name on arrival, the Catching Show block).',
            '#include "asm/field_script.inc"', '#include "pearl.h"', '#include "pearl_story.inc"', '']
    head += [f'    ScriptEntry {e}' for e in entries] + ['    ScriptEntriesEnd', '']
    for i, room in enumerate(rs):
        pedestal_code(c, room, i, tx, d, park_state)
        c('')
        c.at(f'RP_Init_{i}')                          # zone init: the sprites hidden until a slate calls one
        for k, _ in enumerate(room['mons']):
            c(f'    FlagSet {SPRITE_FLAG + k}')
        c('    VMHalt', '')
        c.at(f'RP_Name_{i}')                          # frame table, NAME_WORK == 0: the room's name, as a sign
        c('    ActorsPauseAll', f'    WorkSetConst 0x{NAME_WORK:04X}, 1', '    SEPlay SEQ_SE_MESSAGE',
          f'    InfoMsg {tx.line((room["id"], "room_sign"), fill(d["text"]["room_sign"], room=room["name"]))}, 2',
          '    VMSleep 60', '    InfoMsgClose_0039', '    FinishAllEvents', '    ActorsUnpauseAll', '    VMHalt', '')
        c.at(f'RP_Closed_{i}')                        # frame table, the Catching Show running: back to the park
        c('    pl_LockAll', f'    pl_msg_sys {tx.line(("show_closed",), d["text"]["show_closed"])}', '    pl_WaitButton',
          '    pl_CloseMessage', '    FadeOutBlack', '    FadeWait', '    RTReserveScript PL_RAMANAS_PARK_ARRIVE',
          f'    MapChangeCore PL_RAMANAS_PARK_ZONE, {room["entrance"]["x"]}, 0, {room["entrance"]["z"] + 1}, 1',
          '    FinishAllEvents', '    ActorsUnpauseAll', '    VMHalt', '')
    import pearl_story
    pd = pearl_story.PearlData()
    pp = pd.by_name[d['pal_park']]
    defs = [f'#define PL_RAMANAS_PARK_ZONE {pd.b2_zone[pp["id"]]}   // {d["pal_park"]}',
            f'#define PL_RAMANAS_PARK_ARRIVE {pd.arrival_ids(pp["id"])[1]}   // its file\'s PearlArrive', '']
    c('    .balign 4, 0', 'RP_MovStepBack:', '    Move 0x0D, 1', '    Move 0x00, 1', '    MoveEnd')   # walk south 1, face north (Pearl's codes = Black 2's)
    src = head[:-len(entries) - 2] + defs + head[-len(entries) - 2:] + c.out + ['    .balign 4, 0', '']
    problems = []
    for k, (key, text) in enumerate(zip(tx.index, tx.lines)):
        problems += check_width(text, f'room text {key}')
    text = [f'RamanasRooms_Text_{k:03d} = {b2(t)}' for k, t in enumerate(tx.lines)]
    return src, text, problems


def write():
    d = load()
    src, text, problems = write_rooms()
    for folder, num, ext, body in ((SRC_SCRIPTS, d['files']['script'], '.s', src),
                                   (SRC_TEXT, d['files']['text'], '.txt', text)):
        for old in os.listdir(folder):
            assert not old.startswith(f'{num:04d}_') or old == f'{num:04d}_ramanas_rooms{ext}', \
                f'{folder}/{old} already has number {num}'
        open(os.path.join(folder, f'{num:04d}_ramanas_rooms{ext}'), 'w', encoding='utf-8').write('\n'.join(body) + '\n')
    return problems


