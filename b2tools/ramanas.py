SOLID = 0x01 | 0x81 << 16                    # pearl_chunk.SOLID (class, flags), as pearl_signs


def _build_models():
    from gen4rom import Rom, narc_members
    rom = Rom(os.path.join(ROOT, 'roms', 'pearl.nds'))
    return narc_members(rom.read('fielddata/build_model/build_model.narc'))


_BOX = {}


def model_box(mid):
    """(min x, max x, min z, max z) in units of a Pearl building model's body (flat shapes, the shadows, left out)."""
    if mid not in _BOX:
        import numpy as np, pearl_mesh, pearl_buildings
        pm = pearl_mesh.Model(pearl_buildings.mdl_only(_build_models()[mid]))
        pts = []
        for s in pm.shapes:
            P = np.array([v.pos for t, polys in s.groups for p in polys for v in p], float) * pm.pos_scale / 4096
            if len(P) and P[:, 1].max() - P[:, 1].min() > 2:
                pts.append(P)
        P = np.concatenate(pts)
        _BOX[mid] = (float(P[:, 0].min()), float(P[:, 0].max()), float(P[:, 2].min()), float(P[:, 2].max()))
    return _BOX[mid]


