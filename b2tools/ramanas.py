"""Ramanas Park (BDSP) in Pearl's Pal Park (notes/RAMANAS_PARK.md; user 2026-10-26: "Pal Park: both").

    python3 b2tools/ramanas.py            write the slate rooms' script and text (src/field_scripts/1901_*.s,
                                                src/text/script/1301_*.txt) and check everything offline
    python3 b2tools/ramanas.py check       only the checks (data, names, text widths, entrances, ids)
    python3 b2tools/ramanas.py show        the rooms of the version as resolved (numbers)

Source: data/ramanas_park.json (the rooms, their Pokémon, moves, slates, unlocks, rewards, entrances, looks, text).
Its "version" picks the rooms ('sp' = Pearl NDS, Shining Pearl's exclusives; 'bd' = a Diamond NDS, Brilliant
Diamond's); PEARL_VERSION=bd overrides it. Nothing here is per-version code.

What is made of it:
- The rooms: one zone per room (652-660; 661-662 the Diamond rooms), all on ONE script file (FILE_SCRIPT) and ONE text
  file (FILE_TEXT), written here. Per room i four entries: 1 + 4i the pedestal (sign events on the look's pedestal
  tiles), 2 + 4i the zone init (hides the room's Pokémon sprites: map-local flags), 3 + 4i the room's name shown on
  arrival (frame table: map-local work NAME_WORK == 0), 4 + 4i the Catching Show block (frame table: Pearl's
  VAR_PAL_PARK_STATE == 1: back out to the park). patches/ramanas_park.py writes the zones' headers and events.
- Pearl's two zones (the gate MAP_ROUTE_221_PAL_PARK_ENTRANCE and MAP_PAL_PARK, generated by pearl_story.py) get extra
  entries through pearl_story's hook (gate_code / park_code below): the slate clerk (a new person, pearl_events'
  hook extra_people), the walk-out after a Ramanas visit (the gate's frame table, PVAR_40F3 == 3: frame_rows), and the
  park attendant's line during a visit (talk_override).
- The pedestal: complete room -> "rests in the pedestal"; no slate -> "a slate would fit"; else "Will you place it?",
  the Pokémon (the room's only one; random among the uncaught; the player's choice in the Soul Room), the slate taken,
  the glow (white flash), the Pokémon's Black 2 sprite on the pedestal and its cry, Black 2's static battle
  (CallWildBattleEx: flag 1 a legendary as Black 2's own, flag 8 the hidden ability, Giratina's form 1), and after it:
  caught -> its flag and the room's items (Black 2's item-get, global 2801); Giratina beaten -> its flag and the
  Griseous Orb; lost -> Pearl's park state back to 0 and Black 2's black-out. BDSP's movesets come from the C hook
  (src/pearlb2/ramanas_itcm.c, the table patches/ramanas_park.py writes).
"""
