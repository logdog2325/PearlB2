# script-local works (ov012 ScriptWork 0x8000-0x8061, cleared when a script starts; pearl_story uses 0x8020-0x8046)
T = [0x8050 + i for i in range(8)]
NAME_WORK = 0x401D           # map-local work (cleared on every zone change): the room's name was shown
SPRITE_FLAG = 0x30           # map-local flags 0x30.. (Black 2 clears 0-0x63 on a zone change): the room's sprites
WILD_LEGEND, WILD_HIDDEN_ABILITY = 1, 8     # CallWildBattleEx flags (ov036 field_encount.c CreateStatic)
ITEM_GET = 2801              # Black 2's global "obtained the item" script (0x8000 item, 0x8001 count)
ENTRIES_PER_ROOM = 4
