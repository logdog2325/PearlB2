def check_entrances(ver=None):
    """Each doorway: its body on tiles Pearl already makes solid (no path blocked), all in one chunk, no two
    overlapping, and the tile in front walkable, no tall grass or sand, and reachable from where the gate's scene puts
    the player (PARK_ARRIVAL)."""
    import collections
    m, _ = park_matrix()
    C, B = {}, {}
    for cz, row in enumerate(m['maps']):
        for cx, c in enumerate(row):
            if c == 0xffff:
                continue
            L = json.load(open(os.path.join(ROOT, 'work', 'pearl', 'land', f'{c:03d}.json')))
            for y in range(32):
                for x in range(32):
                    C[(cx * 32 + x, cz * 32 + y)] = L['collision'][y][x] & 1
                    B[(cx * 32 + x, cz * 32 + y)] = L['behaviour'][y][x]
    water = {0x10, 0x11, 0x13, 0x15}
    seen, q = {PARK_ARRIVAL}, collections.deque([PARK_ARRIVAL])
    while q:
        x, y = q.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            t = (x + dx, y + dy)
            if t in C and t not in seen and not C[t] and B[t] not in water:
                seen.add(t)
                q.append(t)
    problems, used = [], {}
    for r, (dx, dz), mid, origin, tiles in entrances(ver):
        name = r['name']
        if any(not C.get(t) for t in tiles):
            problems.append(f'{name}: its doorway covers walkable tiles {[t for t in tiles if not C.get(t)]}')
        if len({(tx // 32, tz // 32) for tx, tz in tiles}) > 1:
            problems.append(f'{name}: its doorway crosses a chunk edge')
        for t in tiles:
            if t in used:
                problems.append(f'{name}: its doorway overlaps {used[t]}\'s at {t}')
            used[t] = name
        f = (dx, dz + 1)
        if f[1] // 32 != dz // 32:
            problems.append(f'{name}: the tile in front of its door {f} is in the next chunk (the model takes its height '
                            f'from the door\'s own chunk)')
        if f not in seen:
            problems.append(f'{name}: the tile in front of its door {f} can\'t be reached from the park\'s entry')
        elif B[f] in (2, 0x21):
            problems.append(f'{name}: tall grass or sand in front of its door {f}')
    return problems


